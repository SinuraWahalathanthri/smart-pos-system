/**
 * Generates Supabase/Postgres DDL from the parsed pos_db.html model.
 *
 * Design decisions that are NOT mechanical translations:
 *
 * 1. `BINARY(16)` -> `uuid`. Postgres has no BINARY(16) and UUID is the native 16-byte type, so the
 *    storage intent is preserved exactly.
 * 2. `DATETIME(3)` -> `timestamptz`. The document says these hold UTC. Postgres `timestamp` does not
 *    carry a zone, and a shop running a till at 18:40 must not silently shift its business date, so
 *    the zoned type is the correct port.
 * 3. `ENUM` -> a named Postgres enum type per column. This keeps the CHECK semantics of the MariaDB
 *    enum and makes the allowed values visible in the catalog.
 * 4. `AUTO_INCREMENT` -> `bigint generated by default as identity`.
 * 5. `BIGINT UNSIGNED` -> `bigint` with a CHECK >= 0, because Postgres has no unsigned integers.
 * 6. MariaDB's implicit UPDATE CURRENT_TIMESTAMP is not portable; `updated_at` is maintained by
 *    trigger instead (see 0006).
 *
 * Tables are emitted in the document's authored order, which is already dependency-sorted
 * (parents before children), so plain CREATE TABLE with inline FKs works without ALTER passes.
 */
import type { Column, Model, Table } from "./design-doc";

/** Columns that are references but whose target the document names in prose, not markup. */

const PG_TYPE: Record<string, string> = {
  "BINARY(16)": "uuid",
  "DATETIME(3)": "timestamptz",
  DATE: "date",
  BOOLEAN: "boolean",
  JSON: "jsonb",
  "CHAR(3)": "char(3)",
  "DECIMAL(6,2)": "numeric(6,2)",
  "DECIMAL(12,3)": "numeric(12,3)",
  "DECIMAL(14,3)": "numeric(14,3)",
  "SMALLINT UNSIGNED": "smallint",
  "TINYINT UNSIGNED": "smallint",
  TINYINT: "smallint",
  SMALLINT: "smallint",
  INT: "integer",
  "BIGINT UNSIGNED": "bigint",
  BIGINT: "bigint",
};

function pgType(c: Column, table: string): string {
  if (c.enumValues?.length) return `${table}_${c.name}_enum`;
  const base = c.mariadbType.trim().replace(/\s+/g, " ");
  if (PG_TYPE[base]) return PG_TYPE[base];
  if (/^VARCHAR\(\d+\)$/i.test(base)) return base.toLowerCase();
  throw new Error(`Unmapped MariaDB type "${c.mariadbType}" on ${table}.${c.name}`);
}

function quoteIdent(s: string): string {
  return `"${s.replace(/"/g, '""')}"`;
}

/** Deterministic, collision-free enum type name. */
function enumTypeName(table: string, column: string): string {
  return `${table}_${column}_enum`;
}

export interface Generated {
  sql: string;
  stats: { tables: number; columns: number; enums: number; indexes: number };
  warnings: string[];
}

/**
 * Sorts tables so every parent precedes its children. The document's authored order groups tables by
 * category, which reads well but is not dependency-sorted (stock_movements precedes product_batches).
 * Ties keep the authored order so output is deterministic.
 */
export function topoSort(model: Model, fks: FkResolution): { order: Table[]; cycles: string[] } {
  const byName = new Map(model.tables.map((t) => [t.name, t]));
  const deps = new Map<string, Set<string>>();

  for (const t of model.tables) {
    const set = new Set<string>();
    for (const c of t.columns) {
      const hit = fks.map[`${t.name}.${c.name}`];
      // Self-references are legal inline in Postgres and must not create an ordering cycle.
      if (hit && hit.table !== t.name && byName.has(hit.table)) set.add(hit.table);
    }
    deps.set(t.name, set);
  }

  const sorted: Table[] = [];
  const placed = new Set<string>();
  const cycles: string[] = [];
  let remaining = [...model.tables];

  while (remaining.length) {
    const ready = remaining.filter((t) =>
      [...(deps.get(t.name) ?? [])].every((d) => placed.has(d) || !deps.has(d)),
    );
    if (!ready.length) {
      // Mutual references: everything left is in a cycle. Emit them in authored order and let the
      // caller add their FKs afterwards via ALTER TABLE.
      for (const t of remaining) cycles.push(t.name);
      sorted.push(...remaining);
      break;
    }
    for (const t of ready) placed.add(t.name);
    sorted.push(...ready);
    remaining = remaining.filter((t) => !placed.has(t.name));
  }

  return { order: sorted, cycles };
}

export function generatePostgres(model: Model): Generated {
  const lines: string[] = [];
  const warnings: string[] = [];
  let enumCount = 0;
  let indexCount = 0;
  const fks = resolveForeignKeys(model);
  for (const a of fks.ambiguous) warnings.push(`ambiguous FK: ${a}`);
  for (const u of fks.unresolved) warnings.push(`unresolved FK: ${u}`);

  const { order: ordered, cycles } = topoSort(model, fks);
  if (cycles.length) warnings.push(`mutually dependent tables (FKs deferred): ${cycles.join(", ")}`);
  // A FK must be deferred whenever its target has not been created yet. That happens only for
  // genuine cycles, since topoSort has already ordered every other dependency correctly.
  const emitted = new Set<string>();
  const deferred: { table: string; column: string; target: string; targetCol: string }[] = [];

  lines.push("-- GENERATED FILE - do not edit by hand.");
  lines.push("-- Source: pos_db.html (BCNF design)");
  lines.push("-- Regenerate: npm run db:plan");
  lines.push("--");
  lines.push("-- Postgres port of the MariaDB design. See tools/ddl.ts for the type mapping rationale.");
  lines.push("");
  lines.push("create extension if not exists pgcrypto;");
  lines.push("");

  // ---- enum types -------------------------------------------------------
  lines.push("-- Enum types (one per ENUM column, preserving the MariaDB CHECK semantics).");
  for (const t of model.tables) {
    for (const c of t.columns) {
      if (!c.enumValues?.length) continue;
      const name = enumTypeName(t.name, c.name);
      const values = c.enumValues.map((v) => `'${v.replace(/'/g, "''")}'`).join(", ");
      lines.push(`create type ${name} as enum (${values});`);
      enumCount++;
    }
  }
  lines.push("");

  // ---- tables -----------------------------------------------------------
  for (const t of ordered) {
    const pk = t.columns.filter((c) => c.pk);
    if (!pk.length) warnings.push(`${t.name}: no PK marked in the design document`);

    const fkMap: Record<string, { table: string; column: string }> = {};
    for (const c of t.columns) {
      const hit = fks.map[`${t.name}.${c.name}`];
      if (hit) fkMap[c.name] = hit;
    }

    const defs: string[] = [];

    for (const c of t.columns) {
      const bits = [quoteIdent(c.name), pgType(c, t.name)];
      const isSinglePk = c.pk && pk.length === 1;
      const target = fkMap[c.name];

      if (isSinglePk) {
        bits.push("not null", "primary key");
        // Surrogate uuid key: generate its own value. A PK that is also an FK (1:1 extension tables
        // like staff_credentials.staff_id) must take the parent's value instead.
        if (c.mariadbType === "BINARY(16)" && !target && /_id$/.test(c.name)) {
          bits.push("default gen_random_uuid()");
        }
      }

      // A column can be both PK and FK: store_settings.store_id is the 1:1 link to stores.
      // Inside a cycle the parent may not exist yet, so the constraint is added after all tables.
      if (target && t.name !== target.table && !emitted.has(target.table)) {
        deferred.push({
          table: t.name,
          column: c.name,
          target: target.table,
          targetCol: target.column,
        });
      } else if (target) {
        bits.push(`references ${quoteIdent(target.table)}(${quoteIdent(target.column)})`);
      } else if (c.fk) {
        warnings.push(`${t.name}.${c.name}: declared FK with no resolvable target`);
      }

      // Unsigned semantics apply to keys too: MariaDB would reject a negative role_id.
      if (/unsigned/i.test(c.mariadbType) && !c.enumValues?.length) {
        bits.push(`check (${quoteIdent(c.name)} >= 0)`);
      }

      if (!isSinglePk) {
        if (/default true/i.test(c.note)) bits.push("default true");
        else if (/default false/i.test(c.note)) bits.push("default false");
        // The design document does not state nullability per column, so only PKs are NOT NULL.
        // Tightening this later is a separate migration, not a guess.
      }

      defs.push("  " + bits.join(" "));
    }

    if (pk.length > 1) {
      defs.push(`  primary key (${pk.map((c) => quoteIdent(c.name)).join(", ")})`);
    }

    lines.push(`-- ${t.order}. ${t.name} (category ${t.category.toUpperCase()})`);
    if (t.purpose) lines.push(`-- ${t.purpose.slice(0, 300)}`);
    lines.push(`create table if not exists ${quoteIdent(t.name)} (`);
    lines.push(defs.join(",\n"));
    lines.push(");");
    emitted.add(t.name);

    // unique constraints
    for (const c of t.columns.filter((x) => x.uq)) {
      lines.push(
        `create unique index if not exists ${quoteIdent(`${t.name}_${c.name}_uq`)} on ${quoteIdent(t.name)} (${quoteIdent(c.name)});`,
      );
      indexCount++;
    }
    // secondary indexes
    for (const c of t.columns.filter((x) => x.ix && !x.pk)) {
      lines.push(
        `create index if not exists ${quoteIdent(`${t.name}_${c.name}_ix`)} on ${quoteIdent(t.name)} (${quoteIdent(c.name)});`,
      );
      indexCount++;
    }
    lines.push("");
  }

  // FKs inside a dependency cycle cannot be inline (the parent table does not exist yet).
  if (deferred.length) {
    lines.push("-- Foreign keys deferred to break table-creation cycles.");
    for (const d of deferred) {
      lines.push(
        `alter table ${quoteIdent(d.table)} add constraint ${quoteIdent(`${d.table}_${d.column}_fk`)} ` +
          `foreign key (${quoteIdent(d.column)}) references ${quoteIdent(d.target)}(${quoteIdent(d.targetCol)});`,
      );
    }
    lines.push("");
  }

  const columns = model.tables.reduce((n, t) => n + t.columns.length, 0);
  return {
    sql: lines.join("\n"),
    stats: { tables: model.tables.length, columns, enums: enumCount, indexes: indexCount },
    warnings,
  };
}

/**
 * Foreign keys are mostly not written as arrows in the design document - the column is marked FK and
 * the target is implied by its name. Resolution order:
 *
 *   1. an explicit arrow in the table FK summary wins;
 *   2. the column name matches a single-column primary key;
 *   3. suffix rules cover the rest (`*_staff_id` -> staff).
 *
 * A name owned by two tables is ambiguous and reported, never guessed: a wrong FK is a schema bug
 * that only shows up at runtime.
 */
const SUFFIX_RULES: { pattern: RegExp; table: string; column: string }[] = [
  { pattern: /^.*_staff_id$/, table: "staff", column: "staff_id" },
  { pattern: /^.*_product_id$/, table: "products", column: "product_id" },
  { pattern: /^.*_store_id$/, table: "stores", column: "store_id" },
  { pattern: /^parent_category_id$/, table: "categories", column: "category_id" },
  { pattern: /^source_receipt_line_id$/, table: "goods_receipt_lines", column: "receipt_line_id" },
];

/** Polymorphic or intentionally unconstrained columns. */
const NOT_A_FK = new Set(["ref_id", "entity_id", "ref_table", "entity_table"]);

export interface FkResolution {
  map: Record<string, { table: string; column: string }>;
  ambiguous: string[];
  unresolved: string[];
}


export function resolveForeignKeys(model: Model): FkResolution {
  // Primary-key name -> owning tables (composite PKs contribute each column name).
  const pkIndex = new Map<string, string[]>();
  for (const t of model.tables) {
    for (const c of t.columns.filter((x) => x.pk)) {
      const list = pkIndex.get(c.name) ?? [];
      if (!list.includes(t.name)) list.push(t.name);
      pkIndex.set(c.name, list);
    }
  }

  const map: Record<string, { table: string; column: string }> = {};
  const ambiguous: string[] = [];
  const unresolved: string[] = [];

  for (const t of model.tables) {
    for (const c of t.columns) {
      if (!c.fk) continue;
      if (NOT_A_FK.has(c.name)) continue;
      const key = `${t.name}.${c.name}`;

      const arrow = [...t.keySummary.matchAll(/([a-z_]+)\s*\u2192\s*([a-z_]+)/g)].find(
        (m) => m[1] === c.name,
      );
      if (arrow) {
        map[key] = { table: arrow[2], column: targetPk(arrow[2], model) };
        continue;
      }

      const owners = (pkIndex.get(c.name) ?? []).filter((o) => o !== t.name);
      const chosen = pickOwner(c.name, owners);
      if (chosen) {
        map[key] = { table: chosen, column: c.name };
        continue;
      }
      if (owners.length > 1) {
        ambiguous.push(`${key} -> ${owners.join(" | ")}`);
        continue;
      }

      const rule = SUFFIX_RULES.find((r) => r.pattern.test(c.name));
      if (rule) {
        map[key] = { table: rule.table, column: rule.column };
        continue;
      }
      unresolved.push(key);
    }
  }
  return { map, ambiguous, unresolved };
}

/**
 * `product_id` is a primary key on both `products` and `product_costs`; the extension table is never
 * the intended referent. Prefer the real entity.
 */
function pickOwner(column: string, owners: string[]): string | null {
  if (owners.length === 0) return null;
  if (owners.length === 1) return owners[0];
  const preferred: Record<string, string> = {
    product_id: "products",
    store_id: "stores",
    staff_id: "staff",
    device_id: "devices",
    sale_id: "sales",
    batch_id: "product_batches",
    pack_size_id: "pack_sizes",
    role_id: "roles",
    permission_id: "permissions",
  };
  return preferred[column] ?? null;
}

function targetPk(table: string, model: Model): string {
  const t = model.tables.find((x) => x.name === table);
  const pk = t?.columns.filter((c) => c.pk) ?? [];
  if (pk.length === 1) return pk[0].name;
  const singular = table.replace(/ies$/, "y").replace(/s$/, "");
  return `${singular}_id`;
}

